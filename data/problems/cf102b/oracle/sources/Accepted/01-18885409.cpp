bool is_prime(long long x) {

	if (x == 1)

		return false;

	for (int i = 2; i * i <= x; i++)

		if (x % i == 0)

			return false;

	return true;



}



bool is_palindrome(string s1) {

	int l = s1.length();

	for (int i = 0; i < l / 2; i++)

		if (s1[i] != s1[l - i - 1])

			return false;



	return true;

}



ull C(ll n, ll k) {

	if (k == 0) return 1;



	return (n * C(n - 1, k - 1)) / k;

}



ll modular_pow(ll base, ll exponent, int modulus) {

	ll result = 1;

	while (exponent > 0) {

		if (exponent % 2 == 1)

			result = (result * base) % modulus;

		exponent = exponent >> 1;

		base = (base * base) % modulus;

	}

	return result;

}



